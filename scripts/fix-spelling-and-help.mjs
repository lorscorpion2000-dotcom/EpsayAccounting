// ═══════════════════════════════════════════════════════════════
// 1) رفع املای فارسی در همه فایلهای TSX/TS
// ═══════════════════════════════════════════════════════════════
const dirs = [
  '/frontend/src/modules/accounting/pages',
  '/frontend/src/modules/settings/pages',
  '/frontend/src/layouts',
];

const spellingFixes = [
  // حروف عربی → فارسی
  ['ك', 'ک'],  // ك عربی → ک فارسی
  ['', 'ی'],  //  عربی → ی فارسی
  ['ﻩ', 'ه'],  // ﻩ عربی → ه فارسی
  // ترکیبهای بدون نیمفاصله (ZWNJ = \u200C)
  ['هزینهها', 'هزینه\u200Cها'],
  ['هزینههای', 'هزینه\u200Cهای'],
  ['درآمدها', 'درآمد\u200Cها'],
  ['درآمدهای', 'درآمد\u200Cهای'],
  ['بدهیها', 'بدهی\u200Cها'],
  ['بدهیهای', 'بدهی\u200Cهای'],
  ['داراییها', 'دارایی\u200Cها'],
  ['داراییهای', 'دارایی\u200Cهای'],
  ['طرف حسابها', 'طرف\u200Cحساب\u200Cها'],
  ['صورتوضعیت', 'صورت\u200Cوضعیت'],
  ['صورتوضعیتها', 'صورت\u200Cوضعیت\u200Cها'],
  ['حسابهای', 'حساب\u200Cهای'],
  ['مطالباتها', 'مطالبات'],
  ['بهروزرسانی', 'به\u200Cروزرسانی'],
  ['کدینگ', 'کدینگ'],
  ['ترازنامه', 'ترازنامه'],
  ['بستانکارها', 'بستانکاران'],
  ['بدهکارها', 'بدهکاران'],
];

let totalFixed = 0;
let filesFixed = 0;

for (const dir of dirs) {
  const fullDir = ROOT + dir;
  if (!fs.existsSync(fullDir)) continue;

  for (const file of fs.readdirSync(fullDir)) {
    if (!file.endsWith('.tsx') && !file.endsWith('.ts')) continue;
    if (file.includes('.bak')) continue;

    const fPath = fullDir + '/' + file;
    let c = fs.readFileSync(fPath, 'utf8');
    const original = c;
    let count = 0;

    for (const [from, to] of spellingFixes) {
      const before = c;
      c = c.split(from).join(to);
      if (c !== before) {
        count += (before.length - c.length) === 0 ? 0 : 1;
      }
    }

    if (c !== original) {
      fs.writeFileSync(fPath, c, 'utf8');
      filesFixed++;
      totalFixed += count;
      console.log('OK ' + file);
    }
  }
}

console.log('');
console.log('فایلهای اصلاحشده: ' + filesFixed);
console.log('');

