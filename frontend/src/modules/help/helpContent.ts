export function getHelpForPath(pathname: string): PageHelp | null {
  if (!pathname) return null;

  if (PAGE_HELP_MAP[pathname]) {
    return PAGE_HELP_MAP[pathname];
  }

  // انطباق مسیرهای فرعی
  for (const [route, help] of Object.entries(PAGE_HELP_MAP)) {
    if (pathname.startsWith(route) && route !== '/') {
      return help;
    }
  }

  // راهنمای عمومی پیش‌فرض
  return {
    title: 'راهنمای کاربری سامانه اپسای',
    description: 'راهنمای کاربری و دستورالعمل استفاده از امکانات این بخش از سامانه.',
    quickStart: ['استفاده از فرم‌های ثبت اطلاعات', 'بررسی صحت مبالغ و کدهای حسابداری', 'ذخیره و ارسال جهت تأیید'],
    sections: [
      {
        title: 'راهنمای عمومی',
        items: [
          'جهت مشاهده آموزش کامل و جامع تمام بخش‌های نرم‌افزار، به منوی «پایه‌ها» ← «راهنمای گردش‌کارها» مراجعه کنید.',
        ],
      },
    ],
  };
}
