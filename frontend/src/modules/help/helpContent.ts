/**
 * دریافت راهنما بر اساس مسیر فعلی
 */
export function getHelpForPath(pathname: string): PageHelp | null {
  // Exact match
  if (HELP_CONTENT[pathname]) return HELP_CONTENT[pathname];

  // Match with pattern (remove trailing IDs)
  const segments = pathname.split('/').filter(Boolean);

  // مسیرهای خاص
  if (pathname.includes('/projects/') && pathname.includes('/edit')) {
    return {
      title: 'ویرایش پروژه',
      description: 'فرم ویرایش اطلاعات پروژه',
      quickStart: ['فیلدهای موردنظر را تغییر دهید', 'روی «ذخیره» کلیک کنید'],
      sections: [],
    };
  }

  if (pathname.match(/\/projects\/[^/]+$/)) {
    return {
      title: 'جزئیات پروژه',
      description: 'تب‌های شناسنامه، قرارداد، WBS و بودجه.',
      sections: [
        {
          title: 'تب‌ها',
          items: [
            'شناسنامه: اطلاعات کامل پروژه',
            'قراردادها: قرارداد کارفرمایی با کسورات',
            'WBS: ساختار چهارسطحی شکست کار',
            'بودجه: سقف بودجه مجاز برای هر ردیف',
          ],
        },
      ],
    };
  }

  if (pathname.match(/\/petty-cash\/[^/]+$/)) {
    return HELP_CONTENT['/petty-cash'];
  }

  if (pathname.match(/\/procurement\/requests\/[^/]+$/)) {
    return HELP_CONTENT['/procurement/requests'];
  }

  if (pathname.match(/\/procurement\/orders\/[^/]+$/)) {
    return HELP_CONTENT['/procurement/orders'];
  }

  if (pathname.match(/\/warehouse\/receipts\/[^/]+$/)) {
    return HELP_CONTENT['/warehouse/receipts'];
  }

  if (pathname.match(/\/warehouse\/issues\/[^/]+$/)) {
    return HELP_CONTENT['/warehouse/issues'];
  }

  // پیدا کردن نزدیک‌ترین مسیر
  for (let i = segments.length; i > 0; i--) {
    const testPath = '/' + segments.slice(0, i).join('/');
    if (HELP_CONTENT[testPath]) return HELP_CONTENT[testPath];
  }

  return null;
}
