import { Injectable, NotFoundException, BadRequestException } from '@nestjs/common';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { PrismaService } from '../../shared/prisma/prisma.service';
import type { DeleteMeta } from '../../common/services/soft-delete.service';

@Injectable()
export class AttachmentsService {
  constructor(private prisma: PrismaService) {}

  async list(entityType: string, entityId: string) {
    if (!entityType || !entityId) {
      throw new BadRequestException('entityType و entityId الزامی هستند');
    }
    return this.prisma.attachment.findMany({
      where: { entityType, entityId },
      orderBy: { createdAt: 'asc' },
      include: {
        uploadedBy: { select: { id: true, fullName: true } },
      },
    });
  }

  async createMany(data: {
    entityType: string;
    entityId: string;
    files: { filename: string; url: string; size?: number; mimetype?: string }[];
    uploadedById?: string;
  }) {
    if (!data.entityType || !data.entityId) {
      throw new BadRequestException('entityType و entityId الزامی هستند');
    }
    if (!data.files || !data.files.length) {
      throw new BadRequestException('حداقل یک فایل الزامی است');
    }
    return this.prisma.attachment.createMany({
      data: data.files.map((f) => ({
        entityType: data.entityType,
        entityId: data.entityId,
        filename: f.filename,
        url: f.url,
        size: f.size,
        mimetype: f.mimetype,
        uploadedById: data.uploadedById,
      })),
    });
  }

  async remove(id: string) {
    const a = await this.prisma.attachment.findUnique({ where: { id } });
    if (!a) throw new NotFoundException('پیوست پیدا نشد');
    if (a.deletedAt) {
      throw new BadRequestException('پیوست قبلاً حذف شده است');
    }
    await this.prisma.attachment.update({
      where: { id },
      data: {
        deletedAt: new Date(),
        deletedBy: null,
      },
    });
    return { success: true, softDeleted: true };
  }

  // ═══════════════════════════════════════════════════════════
  // CRUD extras — soft delete, restore, admin delete
  // Auto-generated by patch-crud-9.mjs
  // ═══════════════════════════════════════════════════════════

  async softDelete(id: string, userId?: string, reason?: string, _meta: DeleteMeta = {}) {
    const existing = await this.prisma.attachment.findUnique({ where: { id } });
    if (!existing) throw new Error('رکورد یافت نشد');
    if (existing.deletedAt) throw new Error('قبلاً حذف شده است');

    await this.prisma.attachment.update({
      where: { id },
      data: {
        deletedAt: new Date(),
        deletedBy: userId || null,
      },
    });

    return { ok: true, id, softDeleted: true, reason: reason || null, deletedBy: userId || null };
  }

  async restore(id: string, userId?: string) {
    const existing = await this.prisma.attachment.findUnique({ where: { id } });
    if (!existing) throw new Error('رکورد یافت نشد');
    if (!existing.deletedAt) throw new Error('رکورد حذف نشده است');

    await this.prisma.attachment.update({
      where: { id },
      data: { deletedAt: null, deletedBy: null },
    });

    return { ok: true, id, restored: true, by: userId || null };
  }

  async adminDelete(id: string, userId?: string, reason?: string, _meta: DeleteMeta = {}) {
    const a = await this.prisma.attachment.findUnique({ where: { id } });
    if (!a) throw new NotFoundException('پیوست پیدا نشد');

    try {
      const urlPath = (a.url || '').replace(/^\/api\/uploads/, '');
      if (urlPath) {
        const fullPath = path.join(process.cwd(), 'uploads', urlPath);
        if (fs.existsSync(fullPath)) {
          fs.unlinkSync(fullPath);
        }
      }
    } catch (e) {
      // silent
    }

    await this.prisma.attachment.delete({ where: { id } });
    return { success: true, hardDeleted: true, id, by: userId || null, reason: reason || null };
  }

}
