import { BadRequestException, Injectable, NotFoundException } from '@nestjs/common';
import { Prisma } from '@prisma/client';
import { PrismaService } from '../../shared/prisma/prisma.service';
import type { DeleteMeta } from '../../common/services/soft-delete.service';
import { CreateCapitalAccountDto } from './dto/capital-account.dto';

@Injectable()
export class CapitalAccountsService {
  constructor(private prisma: PrismaService) {}

  private async generateCode(partnerId: string, projectId?: string): Promise<string> {
    const year = new Date().getFullYear();
    const partner = await this.prisma.partner.findUnique({ where: { id: partnerId } });
    if (!partner) throw new NotFoundException('شریک یافت نشد');

    const count = await this.prisma.partnerCapitalAccount.count();
    const prefix = projectId ? 'PCA' : 'PCC';
    return prefix + '-' + year + '-' + String(count + 1).padStart(4, '0');
  }

  async findAll(query?: { partnerId?: string; projectId?: string; active?: boolean }) {
    const where: Prisma.PartnerCapitalAccountWhereInput = {};
    if (query?.partnerId) where.partnerId = query.partnerId;
    if (query?.projectId) where.projectId = query.projectId;
    if (query?.active !== undefined) where.isActive = query.active;

    return this.prisma.partnerCapitalAccount.findMany({
      where,
      include: {
        partner: { select: { id: true, code: true, name: true, type: true } },
        project: { select: { id: true, code: true, name: true } },
        _count: { select: { contributions: true, withdrawals: true } },
      },
      orderBy: { createdAt: 'desc' },
    });
  }

  async findOne(id: string) {
    const acc = await this.prisma.partnerCapitalAccount.findUnique({
      where: { id },
      include: {
        partner: true,
        project: { select: { id: true, code: true, name: true } },
        _count: { select: { contributions: true, withdrawals: true } },
      },
    });
    if (!acc) throw new NotFoundException('حساب سرمایه یافت نشد');
    return acc;
  }

  async create(dto: CreateCapitalAccountDto) {
    // چک تکراری
    const exists = await this.prisma.partnerCapitalAccount.findFirst({
      where: {
        partnerId: dto.partnerId,
        projectId: dto.projectId || null,
      },
    });
    if (exists) throw new BadRequestException('این حساب قبلاً برای این شریک/پروژه ایجاد شده است');

    const code = await this.generateCode(dto.partnerId, dto.projectId);
    return this.prisma.partnerCapitalAccount.create({
      data: {
        code,
        partnerId: dto.partnerId,
        projectId: dto.projectId,
        notes: dto.notes,
      },
      include: {
        partner: { select: { id: true, name: true } },
        project: { select: { id: true, name: true } },
      },
    });
  }

  async remove(id: string) {
    const acc = await this.findOne(id);
    if (acc._count.contributions > 0 || acc._count.withdrawals > 0) {
      throw new BadRequestException('این حساب دارای گردش است و قابل حذف نیست');
    }
    await this.prisma.partnerCapitalAccount.delete({ where: { id } });
    return { success: true };
  }

  /**
   * پیدا یا ایجاد حساب برای یک شریک/پروژه
   */
  async findOrCreate(partnerId: string, projectId?: string) {
    let acc = await this.prisma.partnerCapitalAccount.findFirst({
      where: { partnerId, projectId: projectId || null },
    });
    if (!acc) {
      acc = await this.prisma.partnerCapitalAccount.create({
        data: {
          code: await this.generateCode(partnerId, projectId),
          partnerId,
          projectId: projectId || null,
        },
      });
    }
    return acc;
  }

  // ═══════════════════════════════════════════════════════════
  // CRUD extras — soft delete, restore, admin delete
  // Auto-generated by patch-crud-9.mjs
  // ═══════════════════════════════════════════════════════════

  async softDelete(id: string, userId?: string, reason?: string, _meta: DeleteMeta = {}) {
    const existing = await this.prisma.partnerCapitalAccount.findUnique({ where: { id } });
    if (!existing) throw new Error('رکورد یافت نشد');
    if (existing.deletedAt) throw new Error('قبلاً حذف شده است');

    await this.prisma.partnerCapitalAccount.update({
      where: { id },
      data: {
        deletedAt: new Date(),
        deletedBy: userId || null,
      },
    });

    return { ok: true, id, softDeleted: true, reason: reason || null, deletedBy: userId || null };
  }

  async restore(id: string, userId?: string) {
    const existing = await this.prisma.partnerCapitalAccount.findUnique({
      where: { id },
      __withDeleted: true,
    } as unknown as Prisma.PartnerCapitalAccountFindUniqueArgs);
    if (!existing) throw new Error('رکورد یافت نشد');
    if (!existing.deletedAt) throw new Error('رکورد حذف نشده است');

    await this.prisma.partnerCapitalAccount.update({
      where: { id },
      data: { deletedAt: null, deletedBy: null },
    });

    return { ok: true, id, restored: true, by: userId || null };
  }

  async adminDelete(id: string, userId?: string, reason?: string, _meta: DeleteMeta = {}) {
    const existing = await this.prisma.partnerCapitalAccount.findUnique({
      where: { id },
      __withDeleted: true,
    } as unknown as Prisma.PartnerCapitalAccountFindUniqueArgs);
    if (!existing) throw new Error('رکورد یافت نشد');

    const contribCount = await this.prisma.partnerCapitalContribution.count({
      where: { accountId: id },
    });
    const withdrawCount = await this.prisma.partnerCapitalWithdrawal.count({
      where: { accountId: id },
    });
    if (contribCount > 0 || withdrawCount > 0) {
      throw new Error(
        'این حساب دارای ' + (contribCount + withdrawCount) + ' رکورد آورده/برداشت است — ابتدا آنها را حذف کنید یا از «آرشیو» استفاده کنید',
      );
    }

    await this.prisma.partnerCapitalAccount.delete({ where: { id } });
    return { ok: true, hardDeleted: true, id, by: userId ?? null, reason: reason ?? null };
  }

  async listDeleted(take = 100, skip = 0) {
    const [items, total] = await Promise.all([
      this.prisma.partnerCapitalAccount.findMany({
        where: { deletedAt: { not: null } },
        orderBy: { deletedAt: 'desc' },
        take: Math.min(take, 500),
        skip,
        __withDeleted: true,
      } as unknown as Prisma.PartnerCapitalAccountFindManyArgs),
      this.prisma.partnerCapitalAccount.count({
        where: { deletedAt: { not: null } },
        __withDeleted: true,
      } as unknown as Prisma.PartnerCapitalAccountCountArgs),
    ]);
    return { items, total, take, skip };
  }
}
